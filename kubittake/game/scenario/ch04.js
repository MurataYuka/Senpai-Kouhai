「……宰相府、ですか」
▷胴元はそう言った、と答えた。
「宝生宰相の慈善基金は、瑠璃浜で一番大きな孤児院を三つ持っています。戴冠の夜のあと、あの人が国を立て直したんです。学校で習います。僕も、試験に書きました」
▷そうか、と言った。
「その基金の金が、影に流れている。……信じられません」
▷信じなくていい、と言った。金の流れは、信じても信じなくても流れる。
迅は、ハンドルを握り直した。
「局に報告します。明日、係長に」
▷報告すればいい、と言った。
「先輩は、どう思いますか」
▷窓の外を見ていた。
運河の向こう、丘の上に、宰相府の白い壁が、魔石の灯りに照らされて浮かんでいた。大聖堂の尖塔の足場が、その隣で黒い骨のように夜空を刺していた。
▷思っていることはない、と言った。まだ会ったことがない人のことは。
「……会ったことがない」
▷遠くから見たことはある。それだけだ、と言った。
迅は、何か引っかかったような顔をした。けれど、それ以上は訊かなかった。
助手席のベルトが、車の揺れに合わせて、かすかに軋んだ。
迅の耳が、また少しだけ赤くなった。
▷何を思い出している、と訊いた。
「何も思い出していません。運転中です」
