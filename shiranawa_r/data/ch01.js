「……住む」
「どちらのお宅に」
▷あなたは、祖母の名前を言った。去年の冬に亡くなって、家が空いているのだと。
彼はしばらく何も言わなかった。
文庫本が、ぱたんと閉じられた。
「……最悪だ」
小さな声だった。あなたに向けた言葉ではないようだった。
▷あなたは、初対面の人間の引っ越しを最悪呼ばわりするのはどうなのかと笑った。
「あ、……いえ。今のは独り言です。聞かなかったことにしてください。聞こえる声で言った僕が悪いんですけど」
