その村では、挨拶の代わりに、ほどけないことを祈る。
そう教えられたのは、もう少しあとのことだ。その日のあなたが知っていたのは、白縄村行きの最終バスが十八時十分に出ることと、祖母の家の鍵が鞄の内ポケットに入っていることだけだった。
平成元年、十月。麓の町の停留所には、錆びたトタンの屋根と、ベンチがひとつあるきりだった。時刻表の「白縄」の欄には数字が四つしか並んでいない。いちばん下の数字に、誰かが赤鉛筆で丸をつけていた。
ベンチの端に先客がいた。
眼鏡をかけた若い男だった。膝の上に文庫本を開いている。表紙には『ツァラトゥストラはかく語りき』とあった。
▷あなたは、このバスは白縄まで行くのかと尋ねた。
彼は本から目を上げた。あなたの顔を見て、足元のボストンバッグを見て、もう一度あなたの顔を見た。
初めて会う人間を見るにしては、少しだけ長かった。
「行きますよ。白縄より先には、どこにも行きませんけど」
「観光なら、やめたほうがいいです。見るものは何もありませんし、宿もないので」
▷あなたは、観光ではない、今日から住むのだと答えた。
