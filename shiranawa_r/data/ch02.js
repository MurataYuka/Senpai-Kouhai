割烹着の柄は覚えている。柿の艶も、新聞紙の見出しも覚えている。名前も聞いた。なのに、顔だけが、どうしても浮かばない。目があった場所も、口があった場所も、思い出そうとすると、そこだけ濡れた紙を撫でたように、つるりと滑った。
