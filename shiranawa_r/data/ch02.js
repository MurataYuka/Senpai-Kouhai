「……読むなら、ご自分で買ってください。文庫なので、そんなに高くないです」
▷あなたは、書き込みのほうが気になったのだと言った。
「書き込みは売ってません」
彼はそれきり黙った。けれど、しばらくして本がまた開かれると、それは少しだけ背もたれの隙間に寄っていた。
頁をめくる速さが、さっきよりも遅くなった。
あなたが一頁を読み終えるころに、ちょうど、次の頁がめくられた。
