六十日目の朝、六時五十九分に扉を叩いた律は、「おはようございます」のあとに、日数を言わなかった。
代わりに、こう言った。
「今日は、棚卸しはしません。書類は、明日から二倍にします」
「消灯の二時間前に、区画Dの突き当たりに来てください。……話します」
それだけ言って、律は背を向けた。
その日一日、律はほとんど姿を見せなかった。朝と午後三時に通信室へ行き、それ以外の時間は自分の部屋にいた。一度だけ、食堂で昼食をとる律を見かけた。律は、いつもの順番で食器を並べ、いつもの順番で食べ、いつもの順番で片付けた。一度も顔を上げなかった。
葛城は、その日も隔離区画の大鳥に会いに行っていた。ガラス越しの二人の旋律は、日ごとに長く、日ごとに揃っていった。
二十時。
あなたは、区画Dの通路を、突き当たりへ向かって歩いた。
あなたの部屋の前を過ぎる。律の部屋の前を過ぎる。黄色と黒の縞の隔壁が近づいてくる。
律は、そこにいた。
金属の板の前の床に、座っていた。
板に、正面から向き合って。

