「六つ目」
律の声が、小さくなった。
「分からないんです」
「あのとき、母は、もう母ではなかったのか。まだ、母だったのか」
「押してと言ったのは、母でした。母の声で、母の言葉で。でも、窓の向こうで笑っていたのは、誰だったのか。僕が押したとき、そこにいたのは、母だったのか。それとも、母の顔をした、別の何かだったのか」
