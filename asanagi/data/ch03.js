十七日目、研究区画の棚卸しの最後の日。
葛城の鼻歌は、日に日に長くなっていた。
最初のころは途切れ途切れだった旋律が、今では一曲分、終わりまで続くようになっていた。終わると、また頭から始まる。本人は、相変わらず気づいていない。気づいて指摘すると、恥ずかしそうに笑って、しばらく黙る。それから、また始まる。
