十四日目の夜、あなたは自室で、ナギの行動記録を読んでいた。
監査官の仕事の一つに、ステーションの運用記録の確認がある。乗員の移動記録、設備の稼働記録、通信の記録。退役前の最後の監査として、過去五年分を抜き取りで確かめることになっていた。
乗員の移動記録は、ナギが自動でつけている。どの区画に、誰が、何時から何時までいたか。通路のセンサーが乗員の拍を拾い、名前と時刻を並べていく。
抜き取りのつもりで、あなたは自分が着任してからの記録を開いた。
自分の名前が並んでいた。
食堂、研究区画、機関区、ハブ。棚卸しの足取りが、そのまま時刻つきで残っている。律の名前がいつもそのすぐ隣にあって、二人分の移動が、ぴったり重なって並んでいた。
