「ナギの記録の誤りかもしれません。センサーの誤作動は、区画Dでは、ないわけではないので。……僕のほうで、調べておきます」
それが本当に誤りだと思っている声には聞こえなかった。
律は、そのまま背を向けかけて、止まった。
