あなたは髪を手でまとめて、後ろへ押さえた。ようやく律の顔が見えた。
眼鏡がなかった。
律の眼鏡は、さっきの衝撃で外れたらしく、二人の頭上をくるくると回りながら、ゆっくり遠ざかっていくところだった。
律は、それに気づいていないようだった。気づいていないのではなく、見えていないのだと、少し遅れて分かった。
眼鏡のない律の目は、思っていたより幼かった。焦点の合わない目が、宙のあちこちをさまよい、片手が空中を泳ぐように探っている。
「すみません、眼鏡を……どこに……」
あなたは手を伸ばして、漂っていた眼鏡を捕まえた。
細い、軽い眼鏡だった。フレームの縁がない。レンズの端が、通路の非常灯を拾って、また薄く青く光った。
