事故は、倉庫を出てすぐに起きた。
帰りの通路で、律の端末から書類が一枚、ふわりと離れた。固定具が甘かったらしい。薄い紙が、ゆっくりと回転しながら、通路の中央へ漂っていく。
あなたは反射的に手を伸ばした。
手すりから、手が離れた。
伸ばした指先は書類に届いた。届いたが、身体のほうが止まらなかった。書類を掴んだ勢いのまま、あなたは通路の真ん中へ、ゆっくりと、しかし確実に流れ出していた。
どこにも触れていない。掴むものがない。
足を伸ばしても、何も蹴れない。自分の身体が、自分の思いどおりにならない場所にある。
「先輩！」
律の声が、初めて大きくなった。
次の瞬間、律が手すりを蹴った。
灰色の作業着が一直線に飛んできて、あなたの腰のあたりに腕が回った。受け止められた、と思ったのも束の間、二人分の勢いが一つになって、今度は二人とも通路を斜めに流れ始めた。
回る。
天井と床の区別がない場所で、世界がゆっくりと一回転する。律の肩越しに手すりが見え、壁が見え、また手すりが見えた。
