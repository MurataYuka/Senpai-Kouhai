棚卸しは、四日目から本格的に始まった。
朝六時五十九分に扉が叩かれ、七時に朝食、七時半に一枚目の書類。備品棚の番号を読み上げ、現物を確かめ、状態を四段階で記入し、監査官の欄に署名する。それを、一日に四十枚から五十枚。
人事記録によれば、案内役の名前は来栖律といった。二十三歳。朝凪生まれ。保守技術員。所長も医務官も彼を律くんと呼ぶので、あなたも頭の中では、いつのまにか律と呼ぶようになっていた。
律の仕事ぶりは、正確という言葉を人の形にしたようだった。
棚の番号は一つも読み飛ばさない。状態の判定に迷ったときは、判定基準の文書を開いて、該当する行を指でなぞってから決める。あなたが署名の欄を一つ飛ばすと、三歩先から振り返って「七番の下です」と言う。見てもいないのに、分かるらしい。
「どうして分かるのかって顔をしていますね」
▷あなたは、実際そう思っていたと認めた。
「先輩のペンの音です。署名は六画、日付は十一画。今のは六画で止まりました」
▷あなたは、それは少し怖いと正直に言った。
「数えているだけです。怖いことは何もしていません」
律は本気でそう思っているようだった。
ただ、一日のうち一度だけ、律が棚卸しの手を止める時間があった。
午後三時。
どの棚の途中でも、どの書類の途中でも、時計が三時を指すと律は端末を閉じ、「保守の時間です」と言って歩き出す。行き先はいつも同じ、ハブの根元にある通信室だった。
「毎日です。着任してから、一日も欠かしたことはありません」
▷あなたは、着任というのは、生まれてからという意味かと冗談を言った。
「……十七のときからです」
律は訂正しなかった。ただ、少しだけ歩く速度を上げた。

