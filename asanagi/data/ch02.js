静かになった。
あなたは律に抱えられたまま、緩衝壁に押しつけられるようにして浮いていた。
律の顔が、すぐ近くにあった。
正確に言えば、律の顔があるはずの場所に、あなたの髪があった。無重力の中で、あなたの髪は一本残らず前へ流れ、律の顔をすっかり覆っていた。
