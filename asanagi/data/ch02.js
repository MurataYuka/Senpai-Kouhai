「くすぐったかったとかではなく、規則上の注意です」
▷あなたは、まだ何も言っていないと指摘した。
「言われる前に言っておきました。規則上の注意です。居住規定第十四条、無重力区画での長い髪は、まとめること。これは衛生と安全のためであって、僕の顔の表面の感覚とは、一切関係がありません」
