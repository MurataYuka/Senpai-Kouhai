五日目の午後、あなたは通信室までついていった。
監査官には、ステーションのすべての設備を見る権限がある。律もそれは分かっているらしく、止めはしなかった。ただ、入口で一度だけ立ち止まって、あなたの靴の裏を確かめた。
「ここは埃を入れないでください。静電気も」
部屋は狭く、暗かった。壁一面に古い受信機と送信機が並び、その前に、一人分の椅子と、一人分の机。机の上のモニターに、細い波がいくつも流れている。
律は椅子に座ると、ひと呼吸も置かずに作業を始めた。
いくつもの窓を開き、数値を読み、別の窓を開き、また数値を読む。指の動きに迷いがない。千回、二千回と繰り返してきた人間の手つきだった。
「外向きの通信の保守です。朝凪から出ていく信号には、ここで雑音除去をかけています。宇宙線とか、機器の癖とか、いろいろ混ざるので」
律は画面の一つを拡大した。
「第三式、係数正常。残差、許容範囲内」
小さな声で、誰に聞かせるでもなく読み上げる。
▷あなたは、第三式というのは何かと尋ねた。
「フィルタの呼び名です。僕が勝手にそう呼んでいるだけです」
画面には、式が一行、表示されていた。
あなたはそれを、何気なく目で追った。
和の記号。周期の変数。減衰の項。窓関数の形。
どこかで見たことがある、と思った。
大学のころ、図書館の古い端末で読んだ、何かの論文だったような気がする。周期的な雑音を、それ以外の雑音から切り分けるための式。どこで読んだのかまでは思い出せない。ただ、式の最後の項の置き方に、妙な懐かしさがあった。
▷あなたは、この式をどこかで見た気がすると呟いた。
律の指が止まった。
ほんの一瞬だった。すぐに画面が切り替わり、式は数字の列の下に隠れた。
「……よくある形なので」
「周期性雑音の分離は、通信課程では基礎です。どこかで見ていても、おかしくありません」
「見ても面白いものではありませんよ、先輩。係数の確認が終わるまで、あと十一分かかります。先に食堂へ戻っていてください」
▷あなたは、待っていると言って、壁際に寄りかかった。
律は何も言わなかった。
それから十一分間、律は一度も振り返らなかった。モニターの青白い光が、律の眼鏡のレンズに映り込んで、細い波の形がいくつも、そこを流れていった。
一度だけ、律が小さく息を吐くのが聞こえた。
「残差、許容範囲内」
十一分きっかりで、律は立ち上がった。

