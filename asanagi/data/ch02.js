七日目は、ハブの倉庫だった。
昇降路を上がるにつれて、身体が軽くなっていく。膝から重さが抜け、肩から抜け、最後には、髪の毛の一本一本が、自分の意志を持ったように浮き上がり始めた。
ハブは回転していない。無重力だった。
円筒形の通路の内側に、手すりが螺旋を描くように張り巡らされている。その手すりを掴んで、引いて、次の手すりへ。律はそれを、まるで平らな廊下を歩くみたいに進んでいく。身体の軸が一度もぶれない。
『ハブへの移動を確認しました。現在の乗員数を更新します。七名』
天井のスピーカーが、あの柔らかな声で言った。
あなたは手すりを掴んだまま、律の背中に尋ねた。
▷あなたは、ナギはまた数え間違えているようだと言った。
「ナギは古いので」
律は振り返らなかった。
一日目とまったく同じ答えだった。同じ言葉を、同じ抑揚で。あらかじめ決めておいた答えを、決めておいたとおりに読み上げたような。
▷あなたは、それは前にも聞いたと言った。
「同じことを訊かれたら、同じことを答えます。そのほうが、正確なので」
倉庫の中は、固定具で壁に留められた箱で埋まっていた。律が番号を読み上げ、あなたが蓋を開けて中を確かめる。予備の空気清浄フィルタ。予備の配線。予備の工具。予備の予備。
▷あなたは、退役したらこれは全部どうなるのかと訊いた。
律は少し考えてから答えた。
「迎えの便に載せられるものは載せます。載せられないものは、朝凪と一緒に、ここに置いていきます」
▷あなたは、置いていかれたものはどうなるのかと重ねた。
「どうもなりません。ずっと、ここにあります」
