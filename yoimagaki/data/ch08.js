　七月に入ると、白籬楼の夜が変わった。
　夜更けになると、あちこちの部屋から、うなされる声が聞こえるようになった。一人ではなかった。二人、三人、四人。細い声、掠れた声、泣きじゃくる声、誰かの名を呼ぶ声。それが、屋根を越えて、写真館の二階まで届いた。
