　九月の十三夜、白籬楼では月見の宴が開かれていた。
　二階の大広間の障子が開け放たれ、薄の穂と団子の三方が並び、客と女たちの笑い声が、月の明るい夜空に吸い込まれていく。楼主は、組合の寄り合いで、宴の途中から大門の外へ出かけていた。お辰は、広間の客あしらいで手が離せない。
「……今夜しか、ないよ」
　台所の暗がりで、朝霧が言った。宴の途中で抜けてきたらしく、裾を少しだけからげていた。
「この下に、穴蔵がある。旦那とお辰しか降りない。鍵は、お辰の帯に下がってる。……写しを取っておいた」
　朝霧は、袂から、真新しい鍵を一本出した。
「どうやって、写しなんか」
「女郎の手先を見くびるんじゃないよ、宵坊。蝋に押しつけて、鍵屋の爺さんに一晩で打たせた。代金は、あたしの簪一本」
　朝霧は、鍵を宵の手袋の手に押しつけた。
「旦那はね、月に一度、夜中にあそこに降りる。お辰と二人で。何をしてるのか、あたしは知らない。知りたくもなかった。……でも、小菊も、花緒も、あそこから旦那が上がってきた次の朝に、起きなかった」
　朝霧は、台所の床の揚げ板を、足で示した。
「半刻だけ、あたしが広間でお辰を引き止めとく。それ以上は、無理だからね」
