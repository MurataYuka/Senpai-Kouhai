@page
夜。
灯番が、今度は街灯の火を一つずつ落としていく。朝と逆の順に、遠いほうから暗くなる。
慧は、牢の見回りを済ませると、獄舎の裏手に出た。
そこに、落とし井の口がある。
石で囲われた、丸い縦穴。縁から覗き込むと、縄梯子が闇の中へ垂れている。その先に返り点があり、さらにその先に上都がある。
今朝、慧はこの穴を降りてきた。
いや――降りて、それから登ってきた。
縄梯子を降りていくうちに、手にかかる体の重さが、少しずつ薄れていった。腕が軽くなり、足が軽くなり、やがて梯子を握っていなくても体がどこへも行かなくなった。
それが、返り点だった。
